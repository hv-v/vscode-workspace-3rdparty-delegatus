#!/usr/bin/env bash
#
# delegatus.sh — build, run and check the offline Delegatus container.
#
# The container serves Delegatus on host loopback, behind an access key, with
# no route off the host. See README.md for the design and what that rules out.
#
# Usage: ./delegatus.sh <command> [options]   ( ./delegatus.sh help )

set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
readonly script_dir
readonly compose_file="${script_dir}/docker-compose.yml"
readonly env_file="${script_dir}/.env"
readonly env_template="${script_dir}/env.example"
readonly secrets_dir="${script_dir}/.secrets"
readonly key_file="${secrets_dir}/token"
readonly masks_file="${script_dir}/compose.masks.yml"
readonly default_config="${script_dir}/workspace.json"

workspace_dir="$(cd -- "${script_dir}/../.." && pwd)"
readonly workspace_dir
readonly source_dir="${workspace_dir}/3rdparty/delegatus"
readonly container_name="${DELEGATUS_CONTAINER:-delegatus}"

# Workspace paths hidden inside the container behind an empty mount: login
# secrets, the corporate Jira/Confluence/GitLab mirrors, and this setup's own
# key and env files. Only paths that exist are masked (a missing bind target
# would be created on the host by dockerd, as root).
readonly mask_paths=(
    .atlassian/.secrets .atlassian/.db .atlassian/.jira .atlassian/.confluence
    .atlassian/.cache .atlassian/navigation_map.md
    .gitlab/.secrets .gitlab/.mr .gitlab/.logs .gitlab/.cache .gitlab/navigation_map.md
    docker/delegatus/.secrets docker/delegatus/.env docker/cbm/.env
)

tmp_files=()
cleanup() {
    local file
    for file in ${tmp_files[@]+"${tmp_files[@]}"}; do
        rm -f -- "$file"
    done
}
trap cleanup EXIT

# Exit codes: 64 usage, 69 unavailable (docker/container), 70 internal failure,
# 78 configuration.
readonly ex_usage=64
readonly ex_unavailable=69
readonly ex_software=70
readonly ex_config=78

log()  { printf '\033[1;34m==>\033[0m %s\n' "$*" >&2; }
warn() { printf '\033[1;33mwarn:\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit "${2:-$ex_software}"; }

usage() {
    cat <<'EOF'
Usage: ./delegatus.sh <command> [options]

Setup
  init                 Write .env and the login key if missing (never overwrites)
  build [--no-cache]   Build the image from 3rdparty/delegatus

Lifecycle
  up                   init, build if needed, start in the background
  down [--volumes]     Stop it; --volumes also drops its state volume
  restart              Recreate the container (picks up .env and a new key)
  status               Container state, HTTP answer and isolation check
  logs [-f]            Container logs

Access
  url                  Print the sign-in link (it carries the key)
  rotate-key           Replace the key and restart; old sessions are refused

  check-isolation      Prove the container cannot resolve names or reach out

Configuration
  configure [FILE]     Apply the defaults in FILE (default workspace.json):
                       operator language and time zone, and one project per
                       repository in the workspace. Safe to re-run.
EOF
}

compose() {
    write_masks
    docker compose --project-directory "$script_dir" -f "$compose_file" -f "$masks_file" "$@"
}

# compose.masks.yml: an empty read-only tmpfs over each masked directory and
# /dev/null over each masked file, at their paths inside the workspace mount.
write_masks() {
    local workspace path target
    workspace=$(env_value DELEGATUS_WORKSPACE || true)
    {
        printf '# Generated by delegatus.sh from mask_paths; do not edit.\n'
        printf 'services:\n  delegatus:\n    volumes:\n'
        if [[ -n "$workspace" && -d "$workspace" ]]; then
            for path in "${mask_paths[@]}"; do
                target="${workspace}/${path}"
                if [[ -d "$target" ]]; then
                    printf '      - type: tmpfs\n        target: "%s"\n        read_only: true\n        tmpfs: { size: 4096, mode: 0 }\n' "$target"
                elif [[ -f "$target" ]]; then
                    printf '      - type: bind\n        source: /dev/null\n        target: "%s"\n        read_only: true\n' "$target"
                fi
            done
        fi
    } > "${masks_file}.new"
    mv -f "${masks_file}.new" "$masks_file"
}

require_docker() {
    command -v docker >/dev/null 2>&1 || die "docker is not installed" "$ex_unavailable"
    docker info >/dev/null 2>&1 || die "the docker daemon is not reachable" "$ex_unavailable"
}

require_source() {
    [[ -f "${source_dir}/package.json" ]] \
        || die "no clone at ${source_dir}; see README.md (Updating the clone)" "$ex_config"
}

# Read one KEY=value from .env without sourcing it.
env_value() {
    local key=$1
    [[ -f "$env_file" ]] || return 1
    sed -n "s/^${key}=//p" "$env_file" | tail -n 1
}

new_key() {
    od -An -N16 -tx1 /dev/urandom | tr -d ' \n'
}

write_key() {
    local key
    key=$(new_key)
    [[ "$key" =~ ^[0-9a-f]{32}$ ]] || die "could not generate an access key"
    ( umask 077; printf '%s\n' "$key" > "${key_file}.new" )
    mv -f "${key_file}.new" "$key_file"
}

cmd_init() {
    install -d -m 700 "$secrets_dir"
    if [[ -f "$key_file" ]]; then
        chmod 600 "$key_file"
    else
        write_key
        log "created the login key in .secrets/token"
    fi

    if [[ -f "$env_file" ]]; then
        log ".env exists; left unchanged"
        return 0
    fi
    [[ -f "$env_template" ]] || die "missing ${env_template}" "$ex_config"
    local claude_dir="${HOME}/.claude/projects" codex_dir="${HOME}/.codex/sessions"
    # A missing bind source would be created by dockerd, owned by root.
    mkdir -p -- "$claude_dir" "$codex_dir"
    sed -e "s|^DELEGATUS_UID=.*|DELEGATUS_UID=$(id -u)|" \
        -e "s|^DELEGATUS_GID=.*|DELEGATUS_GID=$(id -g)|" \
        -e "s|^DELEGATUS_CLAUDE_TRANSCRIPTS=.*|DELEGATUS_CLAUDE_TRANSCRIPTS=${claude_dir}|" \
        -e "s|^DELEGATUS_CODEX_TRANSCRIPTS=.*|DELEGATUS_CODEX_TRANSCRIPTS=${codex_dir}|" \
        -e "s|^DELEGATUS_WORKSPACE=.*|DELEGATUS_WORKSPACE=${workspace_dir}|" \
        "$env_template" > "${env_file}.new"
    chmod 600 "${env_file}.new"
    mv -f "${env_file}.new" "$env_file"
    log "wrote .env from env.example"
}

cmd_build() {
    local -a args=()
    case "${1:-}" in
        "") ;;
        --no-cache) args+=(--no-cache) ;;
        *) die "build: unknown option '$1'" "$ex_usage" ;;
    esac
    require_docker
    require_source
    cmd_init
    log "building the image (first build takes several minutes)"
    compose build ${args[@]+"${args[@]}"}
}

cmd_up() {
    require_docker
    require_source
    cmd_init
    local image
    image=$(env_value DELEGATUS_IMAGE || true)
    if ! docker image inspect "${image:-delegatus:local}" >/dev/null 2>&1; then
        cmd_build
    fi
    compose up -d
    log "starting; './delegatus.sh status' to check, './delegatus.sh url' to sign in"
}

cmd_down() {
    local -a args=()
    case "${1:-}" in
        "") ;;
        --volumes) args+=(--volumes) ;;
        *) die "down: unknown option '$1'" "$ex_usage" ;;
    esac
    require_docker
    compose down ${args[@]+"${args[@]}"}
}

cmd_restart() {
    require_docker
    compose up -d --force-recreate
}

host_port() {
    local port
    port=$(env_value DELEGATUS_HOST_PORT || true)
    printf '%s' "${port:-8898}"
}

cmd_status() {
    require_docker
    local state code
    state=$(docker inspect -f '{{.State.Status}} (restarts: {{.RestartCount}})' "$container_name" 2>/dev/null) \
        || die "no container '${container_name}'; run ./delegatus.sh up" "$ex_unavailable"
    printf 'container:  %s\n' "$state"
    printf 'listening:  http://127.0.0.1:%s/\n' "$(host_port)"
    if command -v curl >/dev/null 2>&1; then
        code=$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 "http://127.0.0.1:$(host_port)/" || true)
        printf 'http:       %s (401/403 without the key is expected)\n' "${code:-no answer}"
    fi
    cmd_check_isolation || true
}

cmd_logs() {
    require_docker
    case "${1:-}" in
        "") compose logs --tail 200 ;;
        -f) compose logs -f --tail 200 ;;
        *) die "logs: unknown option '$1'" "$ex_usage" ;;
    esac
}

cmd_url() {
    [[ -r "$key_file" ]] || die "no key; run ./delegatus.sh init" "$ex_config"
    printf 'http://127.0.0.1:%s/?k=%s\n' "$(host_port)" "$(tr -d '[:space:]' < "$key_file")"
}

cmd_rotate_key() {
    install -d -m 700 "$secrets_dir"
    write_key
    log "replaced the login key"
    if docker inspect "$container_name" >/dev/null 2>&1; then
        cmd_restart
    fi
}

# Run inside the container with its own bun: name resolution and a direct
# connection to a public address must both fail.
cmd_check_isolation() {
    require_docker
    local result
    result=$(docker exec "$container_name" bun -e '
        const dns = await import("node:dns/promises");
        const net = await import("node:net");
        let resolved = "no";
        try { await dns.lookup("example.com"); resolved = "yes"; } catch {}
        const reached = await new Promise((done) => {
            const socket = net.connect({ host: "1.1.1.1", port: 443 });
            const timer = setTimeout(() => { socket.destroy(); done("no"); }, 4000);
            socket.once("connect", () => { clearTimeout(timer); socket.destroy(); done("yes"); });
            socket.once("error", () => { clearTimeout(timer); done("no"); });
        });
        console.log(`${resolved} ${reached}`);
    ' 2>/dev/null) || { warn "isolation check could not run in '${container_name}'"; return 1; }
    local resolved=${result%% *} reached=${result##* }
    printf 'isolation:  dns resolves=%s, internet reachable=%s\n' "$resolved" "$reached"
    if [[ "$resolved" != no || "$reached" != no ]]; then
        warn "the container can reach outside the host — check the network in docker-compose.yml"
        return 1
    fi
}

# ── configure ──────────────────────────────────────────────────

# Every repository the config names: the workspace root itself, then each
# directory matching a `discover` glob that holds a .git, minus `exclude`.
# Prints "name<TAB>absolute root" per line.
config_projects() {
    local config=$1 root_name pattern dir relative
    local -a patterns=() excludes=()
    root_name=$(jq -r '.projects.workspaceRoot // empty' "$config")
    [[ -n "$root_name" ]] && printf '%s\t%s\n' "$root_name" "$workspace_dir"
    mapfile -t patterns < <(jq -r '.projects.discover[]? // empty' "$config")
    mapfile -t excludes < <(jq -r '.projects.exclude[]? // empty' "$config")
    shopt -s nullglob
    for pattern in ${patterns[@]+"${patterns[@]}"}; do
        [[ "$pattern" != /* && "$pattern" != *..* ]] || die "discover entries are workspace-relative globs: '${pattern}'" "$ex_config"
        for dir in "${workspace_dir}"/${pattern}/; do
            dir=${dir%/}
            relative=${dir#"${workspace_dir}/"}
            [[ -e "${dir}/.git" ]] || continue
            [[ " ${excludes[*]-} " == *" ${relative} "* ]] && continue
            printf '%s\t%s\n' "${relative##*/}" "$dir"
        done
    done
    shopt -u nullglob
}

# One call to the running Delegatus with the session in $jar. The key never
# reaches a command line: curl reads it from its config on stdin.
api() {
    local method=$1 path=$2 body=${3:-}
    local -a args=(-s -o "$response_file" -w '%{http_code}' -b "$jar" -X "$method"
        -H "Origin: ${base_url}" -H 'Content-Type: application/json')
    [[ -n "$body" ]] && args+=(--data-binary "$body")
    curl "${args[@]}" "${base_url}${path}" || printf '000'
}

cmd_configure() {
    local config=${1:-$default_config}
    [[ -f "$config" ]] || die "no configuration file ${config}" "$ex_config"
    jq -e . "$config" >/dev/null 2>&1 || die "${config} is not valid JSON" "$ex_config"
    command -v curl >/dev/null 2>&1 || die "curl is required on the host" "$ex_unavailable"
    require_docker
    [[ "$(docker inspect -f '{{.State.Running}}' "$container_name" 2>/dev/null)" == true ]] \
        || die "'${container_name}' is not running; run ./delegatus.sh up" "$ex_unavailable"
    [[ -r "$key_file" ]] || die "no key; run ./delegatus.sh init" "$ex_config"

    base_url="http://127.0.0.1:$(host_port)"
    jar=$(mktemp); tmp_files+=("$jar")
    response_file=$(mktemp); tmp_files+=("$response_file")

    local code
    code=$(printf 'url = "%s/?k=%s"\n' "$base_url" "$(tr -d '[:space:]' < "$key_file")" \
        | curl -s -o /dev/null -w '%{http_code}' -c "$jar" -K - || printf '000')
    [[ "$code" == 307 || "$code" == 200 ]] || die "sign-in refused (HTTP ${code}); is the key current?" "$ex_unavailable"

    local operator
    operator=$(jq -c '.operator // empty | {locale, timeZone} | with_entries(select(.value != null)) | . + (if .locale then {source: "chosen"} else {} end)' "$config")
    if [[ -n "$operator" && "$operator" != "{}" ]]; then
        code=$(api PUT /api/operator/settings "$operator")
        if [[ "$code" == 200 ]]; then
            printf 'operator   %s\n' "$(jq -c '{locale, timeZone}' "$response_file")"
        else
            warn "operator settings refused (HTTP ${code}): $(jq -r '.message // .error // empty' "$response_file" 2>/dev/null)"
        fi
    fi

    local name root error failed=0
    while IFS=$'\t' read -r name root; do
        code=$(api POST /api/projects/create "$(jq -cn --arg name "$name" --arg root "$root" '{name: $name, root: $root}')")
        error=$(jq -r '.error // empty' "$response_file" 2>/dev/null || true)
        case "$code:$error" in
            200:*) printf 'project    %-30s created\n' "$name" ;;
            409:DUPLICATE_PROJECT | 409:DUPLICATE_NAME) printf 'project    %-30s already present\n' "$name" ;;
            *) printf 'project    %-30s refused: HTTP %s %s\n' "$name" "$code" "$error"; failed=1 ;;
        esac
    done < <(config_projects "$config")
    return "$failed"
}

main() {
    [[ $# -ge 1 ]] || { usage; exit "$ex_usage"; }
    local command=$1
    shift
    case "$command" in
        init) cmd_init ;;
        build) cmd_build "$@" ;;
        up) cmd_up ;;
        down) cmd_down "$@" ;;
        restart) cmd_restart ;;
        status) cmd_status ;;
        logs) cmd_logs "$@" ;;
        url) cmd_url ;;
        rotate-key) cmd_rotate_key ;;
        check-isolation) cmd_check_isolation ;;
        configure) cmd_configure "$@" ;;
        help | -h | --help) usage ;;
        *) usage; die "unknown command '${command}'" "$ex_usage" ;;
    esac
}

main "$@"
