#!/usr/bin/env bash
#
# services.sh — build, start, stop and use the search service of the Confluence
# mirror (.atlassian/), independent of wiki's (../wiki/services.sh).
#
# One container (jo-confluence-kb) from the jo-confluence-kb:local image (./Dockerfile), with
# .atlassian/.db and .atlassian/kb/kb.py mounted. .atlassian/kb.sh calls this script,
# so a service started here is the one its searches use. See
# docker-compose.yml for the isolation.
#
# Runs on the macOS system bash (3.2).
#
# Usage: ./services.sh <command> [options]   ( ./services.sh help )

set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
readonly script_dir
workspace_dir="$(cd -- "${script_dir}/../.." && pwd)"
readonly workspace_dir

readonly service="confluence"
readonly mirror_dir="${workspace_dir}/.atlassian"
readonly database="${mirror_dir}/.db/confluence.db"
readonly container="jo-confluence-kb"
image="${KB_IMAGE:-jo-confluence-kb:local}"
readonly image
readonly socket_path="/tmp/kb.sock"   # inside the container
readonly compose_file="${script_dir}/docker-compose.yml"
readonly env_file="${script_dir}/.env"

# Exit codes: 64 usage, 69 unavailable (docker/image/service), 75 no server, 78 config.
readonly ex_usage=64
readonly ex_unavailable=69
readonly ex_no_server=75
readonly ex_config=78

log()  { printf '\033[1;34m==>\033[0m %s\n' "$*" >&2; }
warn() { printf '\033[1;33mwarn:\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31merror:\033[0m %s\n' "$1" >&2; exit "${2:-1}"; }

usage() {
    cat <<EOF
Usage: ./services.sh <command> [options]      (the ${service} search service)

Lifecycle
  build                Build the ${image} image (network at build only)
  up [--idle SECONDS]  Start and wait until it answers. --idle: exit after that
                       long without a request (default 0: stay up until down).
                       Builds the image if missing.
  down                 Stop and remove the container, freeing its memory
  restart              down, then up
  status               State, memory, database
  logs [-f]            Container logs

Use (what ${mirror_dir##*/}/kb.sh calls)
  exec <kb.py args>    Through the running service, e.g. exec search "q"
  run  <kb.py args>    In a one-off container (loads the model each time)

Database:  ${database}
Container: ${container}
EOF
}

require_docker() {
    command -v docker >/dev/null 2>&1 || die "docker is required" "$ex_unavailable"
    docker info >/dev/null 2>&1 || die "the docker daemon is not reachable — is Docker running?" "$ex_unavailable"
    docker compose version >/dev/null 2>&1 || die "the docker compose plugin is required" "$ex_unavailable"
}

# The host user's ids, so the container writes the bind-mounted database as you.
write_env() {
    printf '# generated by services.sh on every run\nKB_UID=%s\nKB_GID=%s\n' "$(id -u)" "$(id -g)" > "${env_file}.new"
    mv -- "${env_file}.new" "$env_file"
}

compose() {
    write_env
    docker compose --file "$compose_file" --project-directory "$script_dir" "$@"
}

running() {
    [[ "$(docker inspect --format '{{.State.Running}}' "$container" 2>/dev/null)" == true ]]
}

have_image() {
    docker image inspect "$image" >/dev/null 2>&1
}

require_database() {
    [[ -f "$database" ]] || die "no database yet — run ${mirror_dir}/sync.sh pull" "$ex_config"
}

cmd_build() {
    require_docker
    log "building ${image}"
    compose build "$service"
}

cmd_up() {
    local idle=0
    while (( $# > 0 )); do
        case "$1" in
            --idle) idle="${2:-}"; shift ;;
            *) die "up: unknown argument '$1'" "$ex_usage" ;;
        esac
        shift
    done
    [[ "$idle" =~ ^[0-9]+$ ]] || die "up: --idle takes a number of seconds" "$ex_usage"
    require_docker
    require_database
    have_image || cmd_build
    log "starting ${container} (loads the model, a few seconds)"
    KB_IDLE="$idle" compose up --detach --wait "$service" \
        || die "${container} did not become healthy — see: $0 logs" "$ex_unavailable"
    log "${service}: ready$( (( idle > 0 )) && printf ', stops after %ss idle' "$idle")"
}

cmd_down() {
    require_docker
    if docker inspect "$container" >/dev/null 2>&1; then
        compose rm --stop --force "$service" >/dev/null 2>&1
        log "${service}: stopped"
    else
        log "${service}: not running"
    fi
}

cmd_status() {
    require_docker
    local state
    if running; then
        state="up ($(docker inspect --format '{{.State.Health.Status}}' "$container" 2>/dev/null)), $(docker stats --no-stream --format '{{.MemUsage}}' "$container")"
    elif docker inspect "$container" >/dev/null 2>&1; then
        state="stopped (exited idle or failed; up starts it again)"
    else
        state="not running"
    fi
    printf '%-10s %s %s\n' container "$container" "$state"
    if [[ -f "$database" ]]; then
        printf '%-10s %s (%s KiB)\n' database "$database" "$(( $(wc -c < "$database") / 1024 ))"
    else
        printf '%-10s %s\n' database "none yet — ${mirror_dir}/sync.sh pull"
    fi
    if have_image; then
        printf '%-10s %s built\n' image "$image"
    else
        printf '%-10s %s not built — %s build\n' image "$image" "$0"
    fi
}

cmd_logs() {
    require_docker
    docker logs --tail 200 "$@" "$container"
}

# Through the running service: kb.py inside the container as the client of the
# server process there. Exits 75 when no server answers.
cmd_exec() {
    running || exit "$ex_no_server"
    docker exec "$container" env KB_SOCKET="$socket_path" python3 /app/kb.py "$@"
}

# A one-off container with the same isolation; loads the model itself.
cmd_run() {
    require_docker
    have_image || die "no ${image} image: run $0 build" "$ex_unavailable"
    require_database
    compose run --rm --no-deps -T "$service" "$@"
}

main() {
    local command="${1:-help}"
    (( $# > 0 )) && shift
    case "$command" in
        build)   cmd_build ;;
        up)      cmd_up "$@" ;;
        down)    cmd_down ;;
        restart) cmd_down; cmd_up "$@" ;;
        status)  cmd_status ;;
        logs)    cmd_logs "$@" ;;
        exec)    cmd_exec "$@" ;;
        run)     cmd_run "$@" ;;
        help|-h|--help) usage ;;
        *) usage >&2; exit "$ex_usage" ;;
    esac
}

main "$@"
